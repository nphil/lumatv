"

# Check required files
MISSING=""
for FILE in $REQUIRED_FILES; do
    if [ ! -e "$FILE" ]; then
        MISSING="$MISSING $FILE"
    fi
done

if [ "$DRY_RUN" = "1" ]; then
    echo "Dry run: checking required inputs"
    echo "Version: $VERSION"
    echo "---"
    for FILE in $REQUIRED_FILES; do
        if [ -e "$FILE" ]; then
            echo "✓ $FILE"
        else
            echo "✗ $FILE (missing)"
        fi
    done
    exit 0
fi

# Real build: fail if any inputs missing
if [ -n "$MISSING" ]; then
    echo "Error: missing required files:$MISSING" >&2
    case "$MISSING" in
        *helper/dist/lumatv-helper*|*helper/dist/plugins/*)
            # Not generated by this script and git-ignored, so a fresh checkout has none; shipping
            # without it would leave Home with no weather or news and say nothing.
            echo "The native helper and the plugin programs beside it are built by helper/build.sh; this package is not built without them." >&2
            ;;
    esac
    case "$MISSING" in
        *ambient/capture/build/arm/lumatv-capture*)
            # Git-ignored like the helper; without it the ambient light would have no picture and say nothing.
            echo "The 32-bit colour reader is built by ambient/capture/build.sh; this package is not built without it." >&2
            ;;
    esac
    case "$MISSING" in
        *jpeg/build/arm/lumatv-jpeg*)
            # Git-ignored like the helper; without it pictures are decoded by the shell, which works, but the hardware block idles.
            echo "The 32-bit picture decoder is built by jpeg/build.sh; this package is not built without it." >&2
            ;;
    esac
    case "$MISSING" in
        *vplane/build/arm/lumatv-vplane*)
            # Git-ignored like the helper; the art saver would keep drawing its own picture and say nothing.
            echo "The 32-bit video-plane player is built by vplane/build.sh (zig); this package is not built without it." >&2
            ;;
    esac
    case "$MISSING" in
        *gfn/feeder/build/arm/lumatv-gfn-feeder*)
            # Git-ignored like the helper; the cameras' live picture would have no program and the helper would say so in its log only.
            echo "The camera feeder is built by gfn/feeder/build.sh (zig); this package is not built without it." >&2
            ;;
    esac
    case "$MISSING" in
        *homestub/build/arm64/lumatv-homestub*)
            # Git-ignored like the helper; without it `lumatv homestub-kind native` would have no program to place and the install would say so only then.
            echo "The native Home stub is built by homestub/build.sh (zig); this package is not built without it." >&2
            ;;
    esac
    case "$MISSING" in
        *rustui/build/card/*)
            # Git-ignored like the helper; the card app is a package of its own and shipping without it would say nothing.
            echo "The card app's programs are built by rustui/tools/build-card.sh; this package is not built without them." >&2
            ;;
    esac
    case "$MISSING" in
        *gfn/build/*)
            # Git-ignored like the helper; without it the round would install a package that has no GeForce NOW app and say nothing.
            echo "The GeForce NOW app's ipk is built by gfn/build-ipk.sh (its header lists the builds it needs); this package is not built without it." >&2
            ;;
    esac
    case "$MISSING" in
        *gfx64/build/*)
            echo "The 64-bit runtime is fetched by gfx64/fetch-blob.sh and built by gfx64/build.sh; the card app is not packed without it." >&2
            ;;
    esac
    exit 1
fi


# Clean build directory
BUILD_DIR="./build"
rm -rf "$BUILD_DIR"
mkdir -p "$BUILD_DIR"

# Fill the brand placeholders in every text file of a staged tree, then fail if
# any placeholder is left, so a misspelt one cannot ship.
render() {
    find "$1" -type f \( -name '*.qml' -o -name '*.js' -o -name '*.css' -o -name '*.json' -o -name '*.html' -o -name '*.sed' -o -name '*.md' \) \
        -exec sed -i \
            -e "s#{{displayName}}#$BRAND_DISPLAY_NAME#g" \
            -e "s#{{shortId}}#$SHORT_ID#g" \
            -e "s#{{appId}}#$APP_ID#g" \
            -e "s#{{dataDir}}#$BRAND_DATA_DIR#g" \
            -e "s#{{qmlModule}}#$BRAND_QML_MODULE#g" {} +
    LEFT=$(grep -rIl '{{[A-Za-z]*}}' "$1" 2>/dev/null || true)
    if [ -n "$LEFT" ]; then
        echo "Error: unresolved placeholders in: $LEFT" >&2
        exit 1
    fi
}

# Rename a staged path to its brand name.
place() {
    [ "$1" = "$2" ] || mv "$1" "$2"
}

# The frame app ($APP_ID.frame, the web half of the Home mini apps) is its own
# ipk, built first and shipped inside the main payload; the tool installs it through
# appInstallService at apply, so there is still one thing for the user to install.
build_ipk() {
    # $1 = package id, $2 = version, $3 = staged data dir, $4 = output path, $5 = description
    pkg_build="$BUILD_DIR/$1"
    rm -rf "$pkg_build"; mkdir -p "$pkg_build/control"
    ( cd "$3" && tar --sort=name --owner=0 --group=0 --numeric-owner --mtime='1970-01-01 00:00:00 UTC' -czf "$OLDPWD/$pkg_build/data.tar.gz" . )
    printf 'Package: %s\nVersion: %s\nArchitecture: all\nMaintainer: nphil\nDescription: %s\n' "$1" "$2" "$5" > "$pkg_build/control/control"
    ( cd "$pkg_build/control" && tar --sort=name --owner=0 --group=0 --numeric-owner --mtime='1970-01-01 00:00:00 UTC' -czf ../control.tar.gz control )
    echo "2.0" > "$pkg_build/debian-binary"
    rm -f "$4"
    ar rc "$4" "$pkg_build/debian-binary" "$pkg_build/control.tar.gz" "$pkg_build/data.tar.gz"
}
FRAME_VERSION=$(grep -o '"version"[[:space:]]*:[[:space:]]*"[^"]*"' frame/appinfo.json | grep -o '[0-9.]*')
FRAME_DATA="$BUILD_DIR/frame-data/usr/palm/applications/$APP_ID.frame"
mkdir -p "$FRAME_DATA"
cp frame/appinfo.json frame/index.html frame/frame.js frame/frame.css frame/icon.png frame/largeIcon.png frame/extraLargeIcon.png frame/Manrope-*.ttf "$FRAME_DATA/"
# The shared web theme (tools/tokens.py web): Lucent's tokens for both materials from the shipped theme.json, and the one face
# the frame's own folder lacks, since the generated stylesheet names all four.
python3 tools/tokens.py payload/theme/theme.json /dev/null web > "$FRAME_DATA/theme.css"
cp payload/fonts/Manrope-Regular.ttf "$FRAME_DATA/"
render "$FRAME_DATA"
mkdir -p "$BUILD_DIR/frame-ipk"
build_ipk "$APP_ID.frame" "$FRAME_VERSION" "$BUILD_DIR/frame-data" "$BUILD_DIR/frame-ipk/$APP_ID.frame.ipk" "$BRAND_DISPLAY_NAME Frame: the web view behind the Home mini apps"

# The card app ($APP_ID.card, the first 64-bit app: docs/research/cardapp-result.md) is an ipk of its own too, shipped inside the main
# payload and installed by tools/cardapp.sh. SAM starts bin/lumatv-card (32-bit: it registers with SAM), which starts bin64/lumatv-card-app
# through gfx64/launch.sh on the app's own copy of the 64-bit runtime (the Debian loader and libraries and the Mali blob, 37 MB).
CARD_VERSION=$(grep -o '"version"[[:space:]]*:[[:space:]]*"[^"]*"' card/appinfo.json | grep -o '[0-9.]*')
CARD_DATA="$BUILD_DIR/card-data/usr/palm/applications/$APP_ID.card"
mkdir -p "$CARD_DATA/bin" "$CARD_DATA/bin64" "$CARD_DATA/gfx64/bundle" "$CARD_DATA/assets/wallpaper"
cp card/appinfo.json card/splash.png card/icon.png card/largeIcon.png card/extraLargeIcon.png "$CARD_DATA/"
cp rustui/build/card/bin/lumatv-card "$CARD_DATA/bin/"
cp rustui/build/card/bin64/lumatv-card-app "$CARD_DATA/bin64/"
cp gfx64/launch.sh gfx64/build/out/heapshim.so "$CARD_DATA/gfx64/"
cp -R gfx64/build/bundle/lib "$CARD_DATA/gfx64/bundle/"
cp payload/wallpaper/wall_1080.png "$CARD_DATA/assets/wallpaper/"
chmod 755 "$CARD_DATA/bin/lumatv-card" "$CARD_DATA/bin64/lumatv-card-app" "$CARD_DATA/gfx64/launch.sh" "$CARD_DATA/gfx64/bundle/lib/ld-linux-aarch64.so.1"
if ! ls "$CARD_DATA"/gfx64/bundle/lib/libmali*.so > /dev/null 2>&1; then
    echo "Error: the 64-bit runtime has no Mali driver; run gfx64/fetch-blob.sh" >&2
    exit 1
fi
render "$CARD_DATA"
mkdir -p "$BUILD_DIR/card-ipk"
build_ipk "$APP_ID.card" "$CARD_VERSION" "$BUILD_DIR/card-data" "$BUILD_DIR/card-ipk/$APP_ID.card.ipk" "$BRAND_DISPLAY_NAME Card: a 64-bit app in its own card window"

# Stage data root: usr/palm/applications/<appId>/
DATA_ROOT="$BUILD_DIR/data/usr/palm/applications/$APP_ID"
mkdir -p "$DATA_ROOT"

# Copy application files (repo root)
cp brand.json "$DATA_ROOT/"
cp appinfo.json "$DATA_ROOT/"
cp index.html "$DATA_ROOT/"
cp app.js "$DATA_ROOT/"
cp launch.js "$DATA_ROOT/"
cp style.css "$DATA_ROOT/"
cp assets/icon.png "$DATA_ROOT/"
cp assets/largeIcon.png "$DATA_ROOT/"
cp assets/extraLargeIcon.png "$DATA_ROOT/"
cp assets/splash.png "$DATA_ROOT/"

# Copy tools with execute bit
mkdir -p "$DATA_ROOT/tools"
cp "tools/$SRC_NAME" "$DATA_ROOT/tools/$SHORT_ID"
chmod 755 "$DATA_ROOT/tools/$SHORT_ID"
cp tools/autostart.sh tools/bootcap.sh "$DATA_ROOT/tools/"
chmod 755 "$DATA_ROOT/tools/autostart.sh" "$DATA_ROOT/tools/bootcap.sh"

# Native UI assets are bundled with the compositor, not the legacy Home tree.
mkdir -p "$DATA_ROOT/payload"
for item in payload/* payload/.[!.]* payload/..?*; do
    [ -e "$item" ] || [ -L "$item" ] || continue
    case "$item" in payload/compositor|payload/home) continue ;; esac
    cp -R "$item" "$DATA_ROOT/payload/"
done
mkdir -p "$DATA_ROOT/payload/compositor/$BRAND_QML_MODULE/icons" "$DATA_ROOT/payload/compositor/$BRAND_QML_MODULE/logo"
cp -R payload/compositor/lumatv/icons/audio "$DATA_ROOT/payload/compositor/$BRAND_QML_MODULE/icons/"
cp payload/compositor/lumatv/logo/arc.png "$DATA_ROOT/payload/compositor/$BRAND_QML_MODULE/logo/"
cp tools/brand.sh "$DATA_ROOT/tools/"
cp tools/logrelay.py "$DATA_ROOT/tools/"
cp tools/tileicons.js "$DATA_ROOT/tools/"
cp tools/keyfilter.py "$DATA_ROOT/tools/"
cp tools/theme.py "$DATA_ROOT/tools/"
cp tools/layout.py "$DATA_ROOT/tools/"
cp tools/tokens.py tools/systemui.py tools/preload.py tools/compositor.sh tools/cardapp.sh tools/gfnapp.sh "$DATA_ROOT/tools/"
cp tools/wake.py "$DATA_ROOT/tools/"
# LG's Content Store theme (tools/lumatv store): the overlay tool, the builder of the script it mounts (which imports tokens, shipped above)
# and the probe's receiver and report (`store probe`). The script's sources, payload/store, go out with the rest of payload/ below.
cp tools/store.sh tools/store_theme.py tools/store_probe.py "$DATA_ROOT/tools/"
cp tools/declutter.sh "$DATA_ROOT/tools/"
chmod 755 "$DATA_ROOT/tools/declutter.sh"
mkdir -p "$DATA_ROOT/payload/helper"
cp helper/dist/lumatv-helper "$DATA_ROOT/payload/helper/"
chmod 755 "$DATA_ROOT/payload/helper/lumatv-helper"
# The Home Assistant plugin (LumaShow's manifest and its program): `lumatv-helper plugin-enable` installs it as a plugin of its own
# uid, which only Nitin's own command does, so nothing here switches it on.
mkdir -p "$DATA_ROOT/payload/plugins/home-assistant/bin"
cp helper/dist/plugins/home-assistant/plugin.json "$DATA_ROOT/payload/plugins/home-assistant/"
cp helper/dist/plugins/home-assistant/bin/home-assistant "$DATA_ROOT/payload/plugins/home-assistant/bin/"
chmod 755 "$DATA_ROOT/payload/plugins/home-assistant/bin/home-assistant"
# The ambient light's colour reader (32-bit, LG's library is) with the LS2 role it needs and the script that installs both.
mkdir -p "$DATA_ROOT/payload/capture"
cp ambient/capture/build/arm/lumatv-capture payload/capture/capture.sh payload/capture/role.json "$DATA_ROOT/payload/capture/"
chmod 755 "$DATA_ROOT/payload/capture/lumatv-capture" "$DATA_ROOT/payload/capture/capture.sh"
# The picture decoder over LG's hardware JPEG block (32-bit, like LG's library); `lumatv` stages it beside the helper.
mkdir -p "$DATA_ROOT/payload/jpeg"
cp jpeg/build/arm/lumatv-jpeg "$DATA_ROOT/payload/jpeg/"
chmod 755 "$DATA_ROOT/payload/jpeg/lumatv-jpeg"
# The art saver's video-plane player (32-bit, like LG's media library) with its clips, the LS2 role it needs and the script that
# installs them. Nothing here installs the role: it is a permission for a new program, so only the owner's `lumatv vplane install` writes it.
mkdir -p "$DATA_ROOT/payload/vplane/clips"
cp vplane/build/arm/lumatv-vplane payload/vplane/vplane.sh payload/vplane/role.json "$DATA_ROOT/payload/vplane/"
cp payload/vplane/clips/* "$DATA_ROOT/payload/vplane/clips/"
chmod 755 "$DATA_ROOT/payload/vplane/lumatv-vplane" "$DATA_ROOT/payload/vplane/vplane.sh"
# The camera feeder (32-bit, the GeForce NOW app's program too) that plays a camera's live picture on the video plane, with the LS2 role it needs and the
# script that installs them. As for the player: the role is a permission for a new program, so only the owner's `lumatv feeder install` writes it.
mkdir -p "$DATA_ROOT/payload/feeder"
cp gfn/feeder/build/arm/lumatv-gfn-feeder payload/feeder/feeder.sh payload/feeder/role.json "$DATA_ROOT/payload/feeder/"
chmod 755 "$DATA_ROOT/payload/feeder/lumatv-gfn-feeder" "$DATA_ROOT/payload/feeder/feeder.sh"
# ... and the decoder libraries of its texture path (FFmpeg's H.264 and H.265 decoders, LGPL, shared: `lib/` beside the program; feeder.sh stages them)
mkdir -p "$DATA_ROOT/payload/feeder/lib"
cp gfn/feeder/build/arm/lib/lib*-lumatv.so.* "$DATA_ROOT/payload/feeder/lib/"
# The native Home stub (docs/research/boot-direct.md, "A native stub"): a static aarch64 program of 13 KB beside its manifest, which the payload
# tree copy above has put here. `lumatv homestub-kind native` stages both over LG's Home directory; nothing in the package does it by itself.
mkdir -p "$DATA_ROOT/payload/homestub-native"
cp homestub/build/arm64/lumatv-homestub "$DATA_ROOT/payload/homestub-native/"
chmod 755 "$DATA_ROOT/payload/homestub-native/lumatv-homestub"
mkdir -p "$DATA_ROOT/payload/frame"
cp "$BUILD_DIR/frame-ipk/$APP_ID.frame.ipk" "$DATA_ROOT/payload/frame/"
mkdir -p "$DATA_ROOT/payload/card"
cp "$BUILD_DIR/card-ipk/$APP_ID.card.ipk" "$DATA_ROOT/payload/card/"
# The GeForce NOW app, as built (it names its build by hash, so nothing here is repacked); `lumatv apply` updates an installed one.
mkdir -p "$DATA_ROOT/payload/gfn"
cp "gfn/build/${GFN_ID}_${GFN_VERSION}_all.ipk" "$DATA_ROOT/payload/gfn/$APP_ID.gfn.ipk"

place "$DATA_ROOT/payload/keyfilter/$SRC_NAME.js" "$DATA_ROOT/payload/keyfilter/$SHORT_ID.js"
place "$DATA_ROOT/payload/webapps/$SRC_NAME.css" "$DATA_ROOT/payload/webapps/$SHORT_ID.css"
render "$DATA_ROOT"

# Create deterministic data.tar.gz
# Use fixed mtime, owner/group 0, sorted filenames
cd "$BUILD_DIR/data"
tar \
    --sort=name \
    --owner=0 --group=0 --numeric-owner \
    --mtime='1970-01-01 00:00:00 UTC' \
    -czf ../data.tar.gz .
cd - > /dev/null

# Create control file
CONTROL_DIR="$BUILD_DIR/control"
mkdir -p "$CONTROL_DIR"
cat > "$CONTROL_DIR/control" << EOF
Package: $APP_ID
Version: $VERSION
Architecture: all
Maintainer: nphil
Description: Native liquid glass home screen for rooted LG webOS TVs
 Draws LumaTV screens with the native compositor and falls back to LG Home.
EOF

# Create deterministic control.tar.gz
cd "$CONTROL_DIR"
tar \
    --sort=name \
    --owner=0 --group=0 --numeric-owner \
    --mtime='1970-01-01 00:00:00 UTC' \
    -czf ../control.tar.gz control
cd - > /dev/null

# Create debian-binary
echo "2.0" > "$BUILD_DIR/debian-binary"

# Create ar archive in deterministic order: debian-binary, control.tar.gz, data.tar.gz
IPK_NAME="${APP_ID}_${VERSION}_all.ipk"
IPK_PATH="$(cd "$REPO_ROOT" && pwd)/$IPK_NAME"
rm -f "$IPK_NAME"
ar rc "$IPK_NAME" \
    "$BUILD_DIR/debian-binary" \
    "$BUILD_DIR/control.tar.gz" \
    "$BUILD_DIR/data.tar.gz"

# Verify the archive
echo "Verifying IPK structure..."
IPK_FULL_PATH="$REPO_ROOT/$IPK_NAME"
AR_MEMBERS=$(ar t "$IPK_FULL_PATH")
EXPECTED_MEMBERS="debian-binary
control.tar.gz
data.tar.gz"

if [ "$AR_MEMBERS" != "$EXPECTED_MEMBERS" ]; then
    echo "Error: IPK members mismatch" >&2
    echo "Expected:" >&2
    echo "$EXPECTED_MEMBERS" >&2
    echo "Got:" >&2
    echo "$AR_MEMBERS" >&2
    exit 1
fi

# Extract and verify contents
VERIFY_DIR="$BUILD_DIR/verify"
mkdir -p "$VERIFY_DIR"
cd "$VERIFY_DIR"
ar x "$IPK_FULL_PATH"
tar -tzf data.tar.gz > data_files.txt
cd - > /dev/null

# Compute IPK hash
IPK_SHA256=$(sha256sum "$IPK_FULL_PATH" | awk '{print $1}')
IPK_SIZE=$(stat -c%s "$IPK_FULL_PATH")

# Report results
echo "✓ IPK built successfully"
echo "File: $IPK_NAME"
echo "Size: $IPK_SIZE bytes"
echo "SHA256: $IPK_SHA256"
echo "---"
echo "Contents (data.tar.gz):"
tar -tzf "$BUILD_DIR/verify/data.tar.gz" | grep -v '^$' | sort
