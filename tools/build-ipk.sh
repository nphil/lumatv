#!/bin/sh
set -e

# IPK builder
# Builds <appId>_<version>_all.ipk without webOS SDK dependency. Every name in
# the package (app id, data dir, QML module dir, tool name, display strings)
# comes from brand.json. Sources carry {{displayName}}, {{shortId}}, {{appId}},
# {{dataDir}} and {{qmlModule}} placeholders that are filled in on the staged
# copy, never in the checkout.

# Determine repo root (this script is tools/build-ipk.sh)
REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO_ROOT"

. "$REPO_ROOT/tools/brand.sh"
brand_load "$REPO_ROOT/brand.json" || exit 1
APP_ID="$BRAND_APP_ID"
SHORT_ID="$BRAND_SHORT_ID"
QML_MODULE="$BRAND_QML_MODULE"

# Names the sources are checked in under. Installed names follow brand.json;
# these only say where to find the files, so a rename never touches them.
SRC_NAME=lumatv

# Parse options
DRY_RUN=0
if [ "$1" = "--dry-run" ]; then
    DRY_RUN=1
fi

# Read version from appinfo.json
VERSION=$(grep -o '"version"[[:space:]]*:[[:space:]]*"[^"]*"' appinfo.json | grep -o '[0-9.]*')
if [ -z "$VERSION" ]; then
    echo "Error: cannot read version from appinfo.json" >&2
    exit 1
fi

# Define required inputs
REQUIRED_FILES="
brand.json
appinfo.json
index.html
app.js
style.css
assets/icon.png
assets/largeIcon.png
assets/splash.png
tools/$SRC_NAME
tools/brand.sh
tools/autostart.sh
tools/keyfilter.py
tools/theme.py
frame/appinfo.json
frame/index.html
frame/frame.js
frame/frame.css
payload/compositor/StarfishFullscreenContainer.qml
payload/compositor/$SRC_NAME/LumaHome.qml
payload/keyfilter/$SRC_NAME.js
payload/webapps/$SRC_NAME.css
payload/home/home.xml
payload/home/en.json.sed
payload/wallpaper/wall_1080.png
payload/theme/theme.json
payload/theme/layout.json
payload/fonts/Manrope-Regular.ttf
payload/fonts/Manrope-Medium.ttf
payload/fonts/Manrope-SemiBold.ttf
payload/fonts/Manrope-Bold.ttf
tools/tokens.py
tools/preload.py
tools/compositor.sh
tools/notification_patch.py
payload/preload.json
payload/homestub/appinfo.json
payload/homestub/index.html
payload/homestub/icon.png
helper/dist/lumatv-helper
ambient/capture/build/arm/lumatv-capture
payload/capture/capture.sh
payload/capture/role.json
tools/cardapp.sh
card/appinfo.json
card/splash.png
rustui/build/card/bin/lumatv-card
rustui/build/card/bin64/lumatv-card-app
gfx64/launch.sh
gfx64/build/out/heapshim.so
gfx64/build/bundle/lib/ld-linux-aarch64.so.1
gfx64/build/bundle/lib/libwayland-client.so.0
"

# Check required files
MISSING=""
for FILE in $REQUIRED_FILES; do
    if [ ! -e "$FILE" ]; then
        MISSING="$MISSING $FILE"
    fi
done

if [ "$DRY_RUN" = "1" ]; then
    echo "Dry run: checking required inputs"
    echo "Version: $VERSION"
    echo "---"
    for FILE in $REQUIRED_FILES; do
        if [ -e "$FILE" ]; then
            echo "✓ $FILE"
        else
            echo "✗ $FILE (missing)"
        fi
    done
    exit 0
fi

# Real build: fail if any inputs missing
if [ -n "$MISSING" ]; then
    echo "Error: missing required files:$MISSING" >&2
    case "$MISSING" in
        *helper/dist/lumatv-helper*)
            # Not generated by this script and git-ignored, so a fresh checkout has none; shipping
            # without it would leave Home with no weather or news and say nothing.
            echo "The native helper is built by helper/build.sh; this package is not built without it." >&2
            ;;
    esac
    case "$MISSING" in
        *ambient/capture/build/arm/lumatv-capture*)
            # Git-ignored like the helper; without it the ambient light would have no picture and say nothing.
            echo "The 32-bit colour reader is built by ambient/capture/build.sh; this package is not built without it." >&2
            ;;
    esac
    case "$MISSING" in
        *rustui/build/card/*)
            # Git-ignored like the helper; the card app is a package of its own and shipping without it would say nothing.
            echo "The card app's programs are built by rustui/tools/build-card.sh; this package is not built without them." >&2
            ;;
    esac
    case "$MISSING" in
        *gfx64/build/*)
            echo "The 64-bit runtime is fetched by gfx64/fetch-blob.sh and built by gfx64/build.sh; the card app is not packed without it." >&2
            ;;
    esac
    exit 1
fi

# Clean build directory
BUILD_DIR="./build"
rm -rf "$BUILD_DIR"
mkdir -p "$BUILD_DIR"

# Fill the brand placeholders in every text file of a staged tree, then fail if
# any placeholder is left, so a misspelt one cannot ship.
render() {
    find "$1" -type f \( -name '*.qml' -o -name '*.js' -o -name '*.css' -o -name '*.json' -o -name '*.html' -o -name '*.sed' -o -name '*.md' \) \
        -exec sed -i \
            -e "s#{{displayName}}#$BRAND_DISPLAY_NAME#g" \
            -e "s#{{shortId}}#$SHORT_ID#g" \
            -e "s#{{appId}}#$APP_ID#g" \
            -e "s#{{dataDir}}#$BRAND_DATA_DIR#g" \
            -e "s#{{qmlModule}}#$QML_MODULE#g" {} +
    LEFT=$(grep -rIl '{{[A-Za-z]*}}' "$1" 2>/dev/null || true)
    if [ -n "$LEFT" ]; then
        echo "Error: unresolved placeholders in: $LEFT" >&2
        exit 1
    fi
}

# Rename a staged path to its brand name.
place() {
    [ "$1" = "$2" ] || mv "$1" "$2"
}

# The frame app ($APP_ID.frame, the web half of the Home mini apps) is its own
# ipk, built first and shipped inside the main payload; the tool installs it through
# appInstallService at apply, so there is still one thing for the user to install.
build_ipk() {
    # $1 = package id, $2 = version, $3 = staged data dir, $4 = output path, $5 = description
    pkg_build="$BUILD_DIR/$1"
    rm -rf "$pkg_build"; mkdir -p "$pkg_build/control"
    ( cd "$3" && tar --sort=name --owner=0 --group=0 --numeric-owner --mtime='1970-01-01 00:00:00 UTC' -czf "$OLDPWD/$pkg_build/data.tar.gz" . )
    printf 'Package: %s\nVersion: %s\nArchitecture: all\nMaintainer: nphil\nDescription: %s\n' "$1" "$2" "$5" > "$pkg_build/control/control"
    ( cd "$pkg_build/control" && tar --sort=name --owner=0 --group=0 --numeric-owner --mtime='1970-01-01 00:00:00 UTC' -czf ../control.tar.gz control )
    echo "2.0" > "$pkg_build/debian-binary"
    rm -f "$4"
    ar rc "$4" "$pkg_build/debian-binary" "$pkg_build/control.tar.gz" "$pkg_build/data.tar.gz"
}
FRAME_VERSION=$(grep -o '"version"[[:space:]]*:[[:space:]]*"[^"]*"' frame/appinfo.json | grep -o '[0-9.]*')
FRAME_DATA="$BUILD_DIR/frame-data/usr/palm/applications/$APP_ID.frame"
mkdir -p "$FRAME_DATA"
cp frame/appinfo.json frame/index.html frame/frame.js frame/frame.css frame/icon.png frame/largeIcon.png frame/Manrope-*.ttf "$FRAME_DATA/"
# The shared web theme (tools/tokens.py web): Lucent's tokens for both materials from the shipped theme.json, and the one face
# the frame's own folder lacks, since the generated stylesheet names all four.
python3 tools/tokens.py payload/theme/theme.json /dev/null web > "$FRAME_DATA/theme.css"
cp payload/fonts/Manrope-Regular.ttf "$FRAME_DATA/"
render "$FRAME_DATA"
mkdir -p "$BUILD_DIR/frame-ipk"
build_ipk "$APP_ID.frame" "$FRAME_VERSION" "$BUILD_DIR/frame-data" "$BUILD_DIR/frame-ipk/$APP_ID.frame.ipk" "$BRAND_DISPLAY_NAME Frame: the web view behind the Home mini apps"

# The card app ($APP_ID.card, the first 64-bit app: docs/research/cardapp-result.md) is an ipk of its own too, shipped inside the main
# payload and installed by tools/cardapp.sh. SAM starts bin/lumatv-card (32-bit: it registers with SAM), which starts bin64/lumatv-card-app
# through gfx64/launch.sh on the app's own copy of the 64-bit runtime (the Debian loader and libraries and the Mali blob, 37 MB).
CARD_VERSION=$(grep -o '"version"[[:space:]]*:[[:space:]]*"[^"]*"' card/appinfo.json | grep -o '[0-9.]*')
CARD_DATA="$BUILD_DIR/card-data/usr/palm/applications/$APP_ID.card"
mkdir -p "$CARD_DATA/bin" "$CARD_DATA/bin64" "$CARD_DATA/gfx64/bundle" "$CARD_DATA/assets/wallpaper"
cp card/appinfo.json card/splash.png assets/icon.png assets/largeIcon.png "$CARD_DATA/"
cp rustui/build/card/bin/lumatv-card "$CARD_DATA/bin/"
cp rustui/build/card/bin64/lumatv-card-app "$CARD_DATA/bin64/"
cp gfx64/launch.sh gfx64/build/out/heapshim.so "$CARD_DATA/gfx64/"
cp -R gfx64/build/bundle/lib "$CARD_DATA/gfx64/bundle/"
cp payload/wallpaper/wall_1080.png "$CARD_DATA/assets/wallpaper/"
chmod 755 "$CARD_DATA/bin/lumatv-card" "$CARD_DATA/bin64/lumatv-card-app" "$CARD_DATA/gfx64/launch.sh" "$CARD_DATA/gfx64/bundle/lib/ld-linux-aarch64.so.1"
if ! ls "$CARD_DATA"/gfx64/bundle/lib/libmali*.so > /dev/null 2>&1; then
    echo "Error: the 64-bit runtime has no Mali driver; run gfx64/fetch-blob.sh" >&2
    exit 1
fi
render "$CARD_DATA"
mkdir -p "$BUILD_DIR/card-ipk"
build_ipk "$APP_ID.card" "$CARD_VERSION" "$BUILD_DIR/card-data" "$BUILD_DIR/card-ipk/$APP_ID.card.ipk" "$BRAND_DISPLAY_NAME Card: a 64-bit app in its own card window"

# Stage data root: usr/palm/applications/<appId>/
DATA_ROOT="$BUILD_DIR/data/usr/palm/applications/$APP_ID"
mkdir -p "$DATA_ROOT"

# Copy application files (repo root)
cp brand.json "$DATA_ROOT/"
cp appinfo.json "$DATA_ROOT/"
cp index.html "$DATA_ROOT/"
cp app.js "$DATA_ROOT/"
cp style.css "$DATA_ROOT/"
cp assets/icon.png "$DATA_ROOT/"
cp assets/largeIcon.png "$DATA_ROOT/"
cp assets/splash.png "$DATA_ROOT/"

# Copy tools with execute bit
mkdir -p "$DATA_ROOT/tools"
cp "tools/$SRC_NAME" "$DATA_ROOT/tools/$SHORT_ID"
chmod 755 "$DATA_ROOT/tools/$SHORT_ID"
cp tools/autostart.sh "$DATA_ROOT/tools/"
chmod 755 "$DATA_ROOT/tools/autostart.sh"

# Copy the payload tree as-is: the tool stages directories (compositor QML,
# theme, fonts) rather than single files.
mkdir -p "$DATA_ROOT/payload"
cp -R payload/. "$DATA_ROOT/payload/"
cp tools/brand.sh "$DATA_ROOT/tools/"
cp tools/tileicons.js "$DATA_ROOT/tools/"
cp tools/keyfilter.py "$DATA_ROOT/tools/"
cp tools/theme.py "$DATA_ROOT/tools/"
cp tools/tokens.py tools/systemui.py tools/systemui_patch.py tools/preload.py tools/compositor.sh tools/notification_patch.py tools/cardapp.sh "$DATA_ROOT/tools/"
mkdir -p "$DATA_ROOT/payload/helper"
cp helper/dist/lumatv-helper "$DATA_ROOT/payload/helper/"
chmod 755 "$DATA_ROOT/payload/helper/lumatv-helper"
# The ambient light's colour reader (32-bit, LG's library is) with the LS2 role it needs and the script that installs both.
mkdir -p "$DATA_ROOT/payload/capture"
cp ambient/capture/build/arm/lumatv-capture payload/capture/capture.sh payload/capture/role.json "$DATA_ROOT/payload/capture/"
chmod 755 "$DATA_ROOT/payload/capture/lumatv-capture" "$DATA_ROOT/payload/capture/capture.sh"
mkdir -p "$DATA_ROOT/payload/frame"
cp "$BUILD_DIR/frame-ipk/$APP_ID.frame.ipk" "$DATA_ROOT/payload/frame/"
mkdir -p "$DATA_ROOT/payload/card"
cp "$BUILD_DIR/card-ipk/$APP_ID.card.ipk" "$DATA_ROOT/payload/card/"

place "$DATA_ROOT/payload/compositor/$SRC_NAME" "$DATA_ROOT/payload/compositor/$QML_MODULE"
place "$DATA_ROOT/payload/keyfilter/$SRC_NAME.js" "$DATA_ROOT/payload/keyfilter/$SHORT_ID.js"
place "$DATA_ROOT/payload/webapps/$SRC_NAME.css" "$DATA_ROOT/payload/webapps/$SHORT_ID.css"
render "$DATA_ROOT"

# Create deterministic data.tar.gz
# Use fixed mtime, owner/group 0, sorted filenames
cd "$BUILD_DIR/data"
tar \
    --sort=name \
    --owner=0 --group=0 --numeric-owner \
    --mtime='1970-01-01 00:00:00 UTC' \
    -czf ../data.tar.gz .
cd - > /dev/null

# Create control file
CONTROL_DIR="$BUILD_DIR/control"
mkdir -p "$CONTROL_DIR"
cat > "$CONTROL_DIR/control" << EOF
Package: $APP_ID
Version: $VERSION
Architecture: all
Maintainer: nphil
Description: Liquid glass home screen for rooted LG webOS TVs
 Reskins the stock LG webOS 10 Home screen with a compositor-level
 liquid glass material, generated abstract wallpaper, and decluttered layout.
EOF

# Create deterministic control.tar.gz
cd "$CONTROL_DIR"
tar \
    --sort=name \
    --owner=0 --group=0 --numeric-owner \
    --mtime='1970-01-01 00:00:00 UTC' \
    -czf ../control.tar.gz control
cd - > /dev/null

# Create debian-binary
echo "2.0" > "$BUILD_DIR/debian-binary"

# Create ar archive in deterministic order: debian-binary, control.tar.gz, data.tar.gz
IPK_NAME="${APP_ID}_${VERSION}_all.ipk"
IPK_PATH="$(cd "$REPO_ROOT" && pwd)/$IPK_NAME"
rm -f "$IPK_NAME"
ar rc "$IPK_NAME" \
    "$BUILD_DIR/debian-binary" \
    "$BUILD_DIR/control.tar.gz" \
    "$BUILD_DIR/data.tar.gz"

# Verify the archive
echo "Verifying IPK structure..."
IPK_FULL_PATH="$REPO_ROOT/$IPK_NAME"
AR_MEMBERS=$(ar t "$IPK_FULL_PATH")
EXPECTED_MEMBERS="debian-binary
control.tar.gz
data.tar.gz"

if [ "$AR_MEMBERS" != "$EXPECTED_MEMBERS" ]; then
    echo "Error: IPK members mismatch" >&2
    echo "Expected:" >&2
    echo "$EXPECTED_MEMBERS" >&2
    echo "Got:" >&2
    echo "$AR_MEMBERS" >&2
    exit 1
fi

# Extract and verify contents
VERIFY_DIR="$BUILD_DIR/verify"
mkdir -p "$VERIFY_DIR"
cd "$VERIFY_DIR"
ar x "$IPK_FULL_PATH"
tar -tzf data.tar.gz > data_files.txt
cd - > /dev/null

# Compute IPK hash
IPK_SHA256=$(sha256sum "$IPK_FULL_PATH" | awk '{print $1}')
IPK_SIZE=$(stat -c%s "$IPK_FULL_PATH")

# Report results
echo "✓ IPK built successfully"
echo "File: $IPK_NAME"
echo "Size: $IPK_SIZE bytes"
echo "SHA256: $IPK_SHA256"
echo "---"
echo "Contents (data.tar.gz):"
tar -tzf "$BUILD_DIR/verify/data.tar.gz" | grep -v '^$' | sort
