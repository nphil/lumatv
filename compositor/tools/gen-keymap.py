#!/usr/bin/env python3
"""Writes the xkb keymap the compositor serves its clients (crates/lumatv-compositor/src/server/keymap.xkb) from LG's own tables.

    gen-keymap.py KEYCODES_LG SYMBOLS_REMOTES > crates/lumatv-compositor/src/server/keymap.xkb

KEYCODES_LG is the set's /usr/share/X11/xkb/keycodes/lg and SYMBOLS_REMOTES its /usr/share/X11/xkb/symbols/lg_vndr/remotes. LG's compositor
builds its keymap from them (QT_WAYLAND_XKB_RULE_NAMES=evdev:lgwebostv:us); a Qt client turns the Linux code of a key event into a keysym
by looking up code + 8 in the keymap it was served, and LG's apps read the keysym as a Qt key (webOS.Key_webOS_ChannelUp is 0x01200021). A key the
keymap has no symbol for reaches an app as Qt key 0, which Live TV ignores.

The output is the keys the remote and the compositor's own tests use (the plain ones below) and every key of LG's `tv` table, one per line; the
`wearable` table, the keys that are not evdev codes (virtual ones above KEY_MAX) and commented-out lines are left out. Python's standard library only.
"""
import re
import sys

# The keys of the plain Linux layout that arrive as themselves: the arrows, OK, Back as KEY_BACK, the digits.
BASE = [
    ("ESC", 9, "Escape"),
    ("AE01", 10, "1"), ("AE02", 11, "2"), ("AE03", 12, "3"), ("AE04", 13, "4"), ("AE05", 14, "5"),
    ("AE06", 15, "6"), ("AE07", 16, "7"), ("AE08", 17, "8"), ("AE09", 18, "9"), ("AE10", 19, "0"),
    ("BKSP", 22, "BackSpace"),
    ("RTRN", 36, "Return"),
    ("SPCE", 65, "space"),
    ("UP", 111, "Up"),
    ("LEFT", 113, "Left"),
    ("RIGHT", 114, "Right"),
    ("DOWN", 116, "Down"),
    ("I166", 166, "XF86Back"),
]

# The kernel's key table on the set is 0x5e0 codes long (the KEY bitmap of every LGE input device); xkb keycodes are Linux codes + 8.
KEYCODE_LIMIT = 0x5e0 + 8


def section(text, kind, name):
    """The body of `kind "name" { ... };`."""
    m = re.search(r'%s\s+"%s"\s*\{' % (kind, re.escape(name)), text)
    if not m:
        sys.exit("%s \"%s\" is not in the file" % (kind, name))
    end = text.index("\n};", m.end())
    return text[m.end():end]


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    codes_text = open(sys.argv[1], encoding="utf-8").read()
    symbols_text = open(sys.argv[2], encoding="utf-8").read()

    codes = {}
    for line in section(codes_text, "xkb_keycodes", "tv").splitlines():
        m = re.match(r"\s*<(\w+)>\s*=\s*(\d+)\s*;", line)
        if m:
            codes[m.group(1)] = int(m.group(2))
    symbols = {}
    for line in section(symbols_text, "xkb_symbols", "base").splitlines():
        m = re.match(r"\s*key\s*<(\w+)>\s*\{\s*\[\s*(0x[0-9a-fA-F]+)\s*\]\s*\}\s*;", line)
        if m:
            symbols[m.group(1)] = int(m.group(2), 16)

    lg = []
    for name, code in codes.items():
        if code >= KEYCODE_LIMIT:
            continue
        if name not in symbols:
            sys.exit("<%s> has a keycode and no symbol" % name)
        lg.append((name, code, "0x%08x" % symbols[name]))
    if not lg:
        sys.exit("no keys read")

    keys = BASE + lg
    names = [k[0] for k in keys]
    numbers = [k[1] for k in keys]
    if len(set(names)) != len(names) or len(set(numbers)) != len(numbers):
        sys.exit("a key name or a keycode is used twice")
    if min(numbers) < 8:
        sys.exit("a keycode below 8")

    out = ["xkb_keymap {"]
    out.append("// LG's webOS keymap (evdev:lgwebostv:us), reduced to the plain keys and LG's `tv` table: generated by compositor/tools/gen-keymap.py.")
    out.append('xkb_keycodes "evdev" {')
    out.append(" minimum = 8;")
    out.append(" maximum = %d;" % max(numbers))
    out += [" <%s> = %d;" % (n, c) for n, c, _ in keys]
    out.append("};")
    out.append('xkb_types "basic" { type "ONE_LEVEL" { modifiers = none; level_name[Level1] = "Any"; }; };')
    out.append('xkb_compatibility "basic" { };')
    out.append('xkb_symbols "basic" {')
    out += [" key <%s> { [ %s ] };" % (n, s) for n, _, s in keys]
    out.append("};")
    out.append("};")
    sys.stdout.write("\n".join(out) + "\n")


main()
